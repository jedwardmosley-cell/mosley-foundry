/** The closest written seat for whatever the person typed: "store owner" is an owner, "youth pastor" a pastor. */
export function seatFor(role: string | null | undefined): Seat {
  const r = (role ?? "").toLowerCase();
  if (/project|program lead|team lead|lead/.test(r) && !/pastor/.test(r)) return "project lead";
  for (const s of ["manager", "owner", "pastor", "parent", "coach"] as const) if (r.includes(s)) return s;
  if (/founder|business|ceo|entrepreneur/.test(r)) return "owner";
  if (/minister|priest|ministry|church/.test(r)) return "pastor";
  if (/mom|dad|mother|father/.test(r)) return "parent";
  if (/supervisor|director|boss/.test(r)) return "manager";
  return "general";
}
